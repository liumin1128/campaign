import { NextRequest } from "next/server";

export const runtime = "nodejs";

type DateRange = {
  start_date: string;
  end_date: string;
};

type RouteInput = {
  origin?: string;
  destination?: string;
  via?: string;
  priority?: number;
};

type BenchmarkRequest = {
  routes?: RouteInput[];
  travel_window?: DateRange;
  currency?: string;
  point_of_sale?: string;
  trip_type?: "round_trip" | "one_way";
  cabin_class?: string;
  stay_rules?: {
    min_nights?: number;
    max_nights?: number;
  };
  competitor_scope?: {
    include_full_service?: boolean;
    include_low_cost?: boolean;
    maximum_competitors?: number;
  };
};

export async function POST(req: NextRequest) {
  let body: BenchmarkRequest;

  try {
    body = (await req.json()) as BenchmarkRequest;
  } catch {
    return Response.json({ error: "Invalid JSON request body" }, { status: 400 });
  }

  const validationError = validateRequest(body);
  if (validationError) {
    return Response.json(validationError, { status: 400 });
  }

  const warnings = [
    "Synthetic benchmark response generated by local integration stub. Replace with a live fare source before production use.",
  ];

  const routeBenchmarks = (body.routes ?? []).map((route, index) => {
    const benchmark = buildSyntheticBenchmark(route, body, index);
    return {
      route: {
        origin: route.origin,
        destination: route.destination,
        ...(route.via ? { via: route.via } : {}),
      },
      lowest_observed_fare: {
        amount: benchmark.lowestObservedFare,
        currency: body.currency,
      },
      reference_market_price: {
        amount: benchmark.referenceMarketPrice,
        currency: body.currency,
      },
      competitor_summary: benchmark.competitorSummary,
      market_position_note: benchmark.marketPositionNote,
      source_reference: benchmark.sourceReference,
      collected_at: new Date().toISOString(),
    };
  });

  return Response.json({
    benchmark_summary: {
      routes_requested: body.routes?.length ?? 0,
      routes_benchmarked: routeBenchmarks.length,
      point_of_sale: body.point_of_sale ?? "unspecified",
      notes: buildSummaryNotes(body),
    },
    route_benchmarks: routeBenchmarks,
    warnings,
  });
}

function validateRequest(body: BenchmarkRequest) {
  const details: string[] = [];

  if (!body.routes || body.routes.length === 0) {
    details.push("routes must contain at least one route.");
  }

  for (const [index, route] of (body.routes ?? []).entries()) {
    if (!route.origin?.trim()) {
      details.push(`routes[${index}].origin is required.`);
    }
    if (!route.destination?.trim()) {
      details.push(`routes[${index}].destination is required.`);
    }
  }

  if (!body.travel_window?.start_date || !body.travel_window?.end_date) {
    details.push("travel_window.start_date and travel_window.end_date are required.");
  }

  if (!body.currency || body.currency.trim().length !== 3) {
    details.push("currency must be a 3-letter ISO code.");
  }

  if (details.length === 0) {
    return null;
  }

  return {
    error: "Validation error",
    details,
  };
}

function buildSyntheticBenchmark(
  route: RouteInput,
  body: BenchmarkRequest,
  index: number,
) {
  const routeKey = [route.origin, route.destination, route.via ?? "", body.point_of_sale ?? ""]
    .join("|")
    .toUpperCase();
  const seed = stableHash(routeKey) + index * 13;
  const cabinMultiplier = getCabinMultiplier(body.cabin_class);
  const tripMultiplier = body.trip_type === "one_way" ? 0.58 : 1;
  const posMultiplier = getPointOfSaleMultiplier(body.point_of_sale);

  const baseFare = (4200 + (seed % 1800)) * cabinMultiplier * tripMultiplier * posMultiplier;
  const referenceMarketPrice = roundCurrency(baseFare);
  const lowestObservedFare = roundCurrency(referenceMarketPrice * (0.92 - ((seed % 4) * 0.01)));
  const competitorClusterLow = roundCurrency(referenceMarketPrice * 0.96);
  const competitorClusterHigh = roundCurrency(referenceMarketPrice * 1.05);
  const competitorCount = Math.max(
    2,
    Math.min(body.competitor_scope?.maximum_competitors ?? 5, 6),
  );

  return {
    referenceMarketPrice,
    lowestObservedFare,
    competitorSummary:
      `Synthetic benchmark cluster for ${route.origin}-${route.destination} shows ${competitorCount} comparable fares around ` +
      `${formatMoney(competitorClusterLow, body.currency)} to ${formatMoney(competitorClusterHigh, body.currency)}.`,
    marketPositionNote:
      `Use this stub only for integration testing. A tactical offer below ${formatMoney(referenceMarketPrice, body.currency)} ` +
      `would likely appear competitive in the simulated market set.`,
    sourceReference:
      `synthetic_benchmark:${body.point_of_sale ?? "NA"}:${route.origin}-${route.destination}:${new Date().toISOString().slice(0, 10)}`,
  };
}

function buildSummaryNotes(body: BenchmarkRequest) {
  return [
    `Synthetic benchmark mode for ${body.trip_type ?? "round_trip"} ${body.cabin_class ?? "all-cabin"} search context.`,
    `Point of sale: ${body.point_of_sale ?? "unspecified"}.`,
    "Replace this endpoint with a live market fare provider before production rollout.",
  ];
}

function stableHash(value: string) {
  let hash = 0;
  for (let index = 0; index < value.length; index += 1) {
    hash = (hash * 31 + value.charCodeAt(index)) >>> 0;
  }
  return hash;
}

function getCabinMultiplier(cabinClass?: string) {
  switch ((cabinClass ?? "economy").toLowerCase()) {
    case "premium_economy":
    case "premium economy":
      return 1.35;
    case "business":
      return 2.45;
    case "first":
      return 3.8;
    default:
      return 1;
  }
}

function getPointOfSaleMultiplier(pointOfSale?: string) {
  switch ((pointOfSale ?? "").toUpperCase()) {
    case "SG":
      return 1.04;
    case "CN":
      return 0.98;
    case "AU":
      return 1.07;
    case "US":
      return 1.12;
    default:
      return 1;
  }
}

function roundCurrency(value: number) {
  return Math.round(value / 10) * 10;
}

function formatMoney(value: number, currency?: string) {
  return `${currency ?? "CUR"} ${value.toFixed(0)}`;
}